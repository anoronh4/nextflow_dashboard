#!/usr/bin/env python3
"""Bundle src/ into the single self-contained pipeline_dashboard_offline.html.

    python3 build.py           write pipeline_dashboard_offline.html
    python3 build.py --check   exit 1 if pipeline_dashboard_offline.html is out of date with src/

Standard library only. Every local <link rel="stylesheet" href="..."> and <script src="..."></script>
line in src/index.html is replaced by an inline <style>/<script> holding that file, in document order,
so the output works offline from a single file. Edit src/, never the generated file.
"""
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent
SRC = ROOT / 'src'
OUT = ROOT / 'pipeline_dashboard_offline.html'
BANNER = '<!-- GENERATED by build.py from src/ — edit src/, then run python3 build.py -->\n'
CSS_TAG = re.compile(r'^(\s*)<link rel="stylesheet" href="([^"]+)">\s*$')
JS_TAG = re.compile(r'^(\s*)<script src="([^"]+)"></script>\s*$')


def read(path):
    """Text of path, with newlines left exactly as stored (no translation)."""
    with open(path, encoding='utf-8', newline='') as f:
        return f.read()


def inline(rel, closing):
    """Contents of src/<rel>, refusing anything that would break offline use or the inline block."""
    if '://' in rel or rel.startswith(('/', '//')):
        sys.exit(f'build.py: {rel!r} is not a local file; the bundle must work offline')
    if not (SRC / rel).is_file():
        sys.exit(f'build.py: src/{rel} not found (referenced from src/index.html)')
    text = read(SRC / rel)
    if closing in text.lower():
        sys.exit(f'build.py: src/{rel} contains {closing!r}, which would end the inline block early')
    return text if text.endswith('\n') else text + '\n'


def build():
    parts = []
    for line in read(SRC / 'index.html').splitlines(keepends=True):
        if m := CSS_TAG.match(line):
            indent, rel = m.groups()
            parts.append(f'{indent}<!-- src/{rel} -->\n{indent}<style>\n{inline(rel, "</style")}</style>\n')
        elif m := JS_TAG.match(line):
            indent, rel = m.groups()
            parts.append(f'{indent}<!-- src/{rel} -->\n{indent}<script>\n{inline(rel, "</script")}</script>\n')
        else:
            if re.search(r'<script\b[^>]*\bsrc\s*=|<link\b[^>]*\bstylesheet', line, re.I):
                sys.exit(f'build.py: unrecognised asset tag in src/index.html: {line.strip()!r} '
                         '(use exactly <script src="..."></script> or <link rel="stylesheet" href="...">, one per line)')
            parts.append(line)
    html = ''.join(parts)
    if not html.lower().startswith('<!doctype html>'):
        sys.exit('build.py: src/index.html must start with <!DOCTYPE html>')
    after_doctype = html.index('\n') + 1          # nothing may come before <!DOCTYPE html>
    return html[:after_doctype] + BANNER + html[after_doctype:]


def main():
    args = sys.argv[1:]
    if args not in ([], ['--check']):
        sys.exit(__doc__)
    html = build()
    if args:
        current = read(OUT) if OUT.exists() else None
        if current != html:
            sys.exit('build.py --check: pipeline_dashboard_offline.html is out of date; run python3 build.py')
        print('build.py --check: up to date')
        return
    with open(OUT, 'w', encoding='utf-8', newline='') as f:
        f.write(html)
    print(f'wrote {OUT.name} ({len(html.encode()) / 1e6:.1f} MB)')


if __name__ == '__main__':
    main()
